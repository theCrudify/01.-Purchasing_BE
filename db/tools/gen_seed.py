#!/usr/bin/env python3
"""Generate db/migrations/0100_seed.sql from the SQL Server seeds of the redesign (status transitions in scope, currencies)."""
import re, sys, pathlib
src = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
SCOPE = {'SVR', 'PR', 'RFQ', 'QUO', 'CTR', 'PO', 'GR'}  # purchasing + vendor portal
pg = lambda s: s.replace("N'", "'")

tr = (src / 'seed_status_transition.sql').read_text()
rows = re.findall(r"^\s*\(('(\w+)',.*?)\),?\s*$", tr, re.M)
rows = [pg(r[0]) for r in rows if r[1] in SCOPE]
rows = [re.sub(r", ([01]), ('|NULL)", lambda m: f", {'true' if m.group(1)=='1' else 'false'}, {m.group(2)}", r) for r in rows]

cur = (src / 'seed_currency.sql').read_text()
crow = [pg(r) for r in re.findall(r"^\s*\(('[A-Z]{3}'.*?)\),?\s*$", cur, re.M)]
def boolify(r):  # last two ints = IsFund, IsActive
    head, fund, act = r.rsplit(', ', 2)
    return f"{head}, {'true' if fund=='1' else 'false'}, {'true' if act=='1' else 'false'}"
crow = [boolify(r) for r in crow]

out.write_text(f"""-- GENERATED by db/tools/gen_seed.py from ../02. KPIN_DB_REDESIGN/prisma/sql — do not edit by hand.
-- Status transitions for in-scope document types ({', '.join(sorted(SCOPE))}): {len(rows)} rows. Replaces the matrix for those types.
DELETE FROM mst_status_transition WHERE "DocType" IN ({', '.join(f"'{t}'" for t in sorted(SCOPE))});
INSERT INTO mst_status_transition ("DocType","FromStatus","ToStatus","RequiredApproval","AllowBp","Description") VALUES
""" + ",\n".join(f"  ({r})" for r in rows) + """;

-- ISO 4217 currencies (""" + str(len(crow)) + """). Never deletes; IsActive is only set on first insert.
INSERT INTO mst_currency ("Code","NumericCode","Name","Symbol","Decimals","IsFund","IsActive") VALUES
""" + ",\n".join(f"  ({r})" for r in crow) + """
ON CONFLICT ("Code") DO UPDATE SET "NumericCode"=EXCLUDED."NumericCode","Name"=EXCLUDED."Name","Symbol"=EXCLUDED."Symbol","Decimals"=EXCLUDED."Decimals","IsFund"=EXCLUDED."IsFund";
""")
print(len(rows), 'transitions,', len(crow), 'currencies')
